import Foundation

/// Privacy and size rules shared by capture, storage and reuse. Ported from `clipboard_history.rs`.
enum ClipboardPolicy {
    static func shouldCapture(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        return !trimmed.isEmpty && text.utf8.count <= ClipboardLimits.maxTextBytes && !looksSensitive(trimmed)
    }

    /// Obvious credentials only. Unmarked sensitive text can still be saved.
    static func looksSensitive(_ text: String) -> Bool {
        let lower = text.lowercased()
        let markers = [
            "password=", "password:", "passwd=", "api_key=", "api-key:", "client_secret=", "client-secret:",
            "access_token=", "refresh_token=", "authorization: bearer ",
        ]
        if markers.contains(where: lower.contains) { return true }
        if lower.hasPrefix("-----begin ") && lower.contains("private key-----") { return true }

        let compact = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let tokenPrefixes = ["ghp_", "gho_", "ghu_", "ghs_", "github_pat_", "sk-", "xoxb-", "xoxp-"]
        if tokenPrefixes.contains(where: compact.hasPrefix) { return true }
        if compact.hasPrefix("AKIA") && compact.utf8.count == 20 && compact.allSatisfy({ $0.isASCII && ($0.isLetter || $0.isNumber) }) {
            return true
        }
        let parts = compact.split(separator: ".", omittingEmptySubsequences: false)
        return parts.count == 3 && parts.allSatisfy { part in
            part.utf8.count >= 8 && part.allSatisfy { $0.isASCII && ($0.isLetter || $0.isNumber || $0 == "-" || $0 == "_" || $0 == "=") }
        }
    }

    /// Pasteboard types that password managers and other apps use to keep content out of clipboard history.
    static func isPrivateType(_ type: String) -> Bool {
        let kind = type.lowercased()
        let known: Set<String> = [
            "org.nspasteboard.concealedtype", "org.nspasteboard.transienttype", "org.nspasteboard.autogeneratedtype",
            "org.nspasteboard.private", "org.nspasteboard.privatetype", "com.apple.is-remote-clipboard",
            "de.petermaurer.transient-pasteboard-type", "com.typeit4me.clipping", "com.agilebits.onepassword",
        ]
        return known.contains(kind) || kind.contains("concealed") || kind.contains("transient")
            || kind.hasSuffix(".private") || kind.hasSuffix(".privatetype")
    }

    static func displayPreview(_ text: String) -> String {
        guard text.count > ClipboardLimits.searchPreviewCharacters else { return text }
        return String(text.prefix(ClipboardLimits.searchPreviewCharacters)) + "…"
    }

    static func validDimensions(width: Int, height: Int) -> Bool {
        width > 0 && height > 0
            && width <= ClipboardLimits.maxImageDimension && height <= ClipboardLimits.maxImageDimension
            && width * height <= ClipboardLimits.maxImagePixels
    }

    /// Parses local `file:` URLs without touching the file system.
    static func parseFileReferences(_ urls: [String]) throws(ClipboardError) -> [String] {
        guard !urls.isEmpty, urls.count <= ClipboardLimits.maxFileReferences,
              urls.reduce(0, { $0 + $1.utf8.count }) <= ClipboardLimits.maxReferenceBytes
        else { throw .referenceLimit }
        var paths: [String] = []
        for value in urls {
            guard let url = URL(string: value), let scheme = url.scheme else { throw .invalidReference }
            let host = url.host(percentEncoded: false) ?? ""
            guard scheme.lowercased() == "file", host.isEmpty || host == "localhost", url.query == nil, url.fragment == nil else {
                throw .localReferencesOnly
            }
            let path = url.path(percentEncoded: false)
            guard path.hasPrefix("/") else { throw ClipboardError("Invalid local file reference.") }
            paths.append(path)
        }
        return paths
    }

    /// Checks that every referenced file still exists. Run outside the store lock.
    static func validateFileReferences(_ urls: [String]) throws(ClipboardError) -> [String] {
        let paths = try parseFileReferences(urls)
        guard paths.allSatisfy({ FileManager.default.fileExists(atPath: $0) }) else { throw .missingFile }
        return paths
    }

    /// Validation done before a copy or paste, off the main thread.
    static func prepare(_ payload: ClipboardPayload) throws(ClipboardError) -> ClipboardPayload {
        if case .files(let urls) = payload { _ = try validateFileReferences(urls) }
        return payload
    }
}
